def require(condition, error):
    if not condition:
        raise ValueError(error)


def sha(data):
    return hashlib.sha256(data).hexdigest()


def digest(value):
    return sha(json.dumps(value, sort_keys=True, separators=(",", ":"), ensure_ascii=False).encode())


def local(place):
    kind = place["kind"]
    if "Local" in kind:
        return kind["Local"]
    path, projection = kind["Projection"]
    require(projection == "Deref", "unexpected place projection")
    return local(path)


def constants(document):
    found = {}

    def visit(value):
        if isinstance(value, dict):
            if set(value) == {"Value"} and isinstance(value["Value"], list) and len(value["Value"]) == 2:
                ident, definition = value["Value"]
                if isinstance(definition, list) and len(definition) == 2 and isinstance(definition[0], dict) and "Integer" in definition[0]:
                    previous = found.setdefault(ident, definition)
                    require(previous == definition, "ambiguous literal declaration")
            for child in value.values():
                visit(child)
        elif isinstance(value, list):
            for child in value:
                visit(child)

    visit(document)
    return found


class Compiler:
    def __init__(self, literals, locals):
        self.literals = literals
        self.locals = locals.copy()
        self.code = []

    def emit(self, slot, expression, effect=False):
        op = "←" if effect else ":="
        self.code.append(f"  let v{slot} {op} {expression}")
        self.locals[slot] = f"v{slot}"

    def value(self, operand):
        key, value = next(iter(operand.items()))
        if key == "Const":
            definition = self.literals[value["Deduplicated"]] if "Deduplicated" in value else value["Value"][1]
            integer = definition[0]["Integer"]["Unsigned"]
            require(integer[0] in ("Usize", "U8"), "unexpected literal width")
            return str(int(integer[1]))
        require(key in ("Move", "Copy"), "unexpected operand")
        kind = value["kind"]
        if "Projection" in kind and kind["Projection"][1] == {"Field": [1, 0]}:
            require(key == "Copy" and local(kind["Projection"][0]) == 11, "unexpected option payload")
            return "offset"
        slot = local(value)
        return self.locals.pop(slot) if key == "Move" else self.locals[slot]

    def assign(self, slot, value):
        if "Ref" in value:
            self.locals[slot] = self.locals[local(value["Ref"]["place"])]
        elif "Use" in value:
            self.locals[slot] = self.value(value["Use"][0])
        elif "Aggregate" in value:
            bounds = value["Aggregate"][1]
            require(len(bounds) == 2, "range bounds changed")
            lo, hi = map(self.value, bounds)
            self.emit(slot, f"({lo}, {hi})")
        else:
            operator, lhs, rhs = value["BinaryOp"]
            lhs, rhs = self.value(lhs), self.value(rhs)
            if operator == {"Sub": "Panic"}:
                self.emit(slot, f"checkedSub {lhs} {rhs}", True)
            elif operator in ({"Add": "Panic"}, {"Mul": "Panic"}):
                sign = "+" if "Add" in operator else "*"
                self.emit(slot, f"checked ({lhs} {sign} {rhs})", True)
            else:
                require(operator == "Ne" and rhs == "0" and lhs == "testSelfNonzero state.any",
                        "final mask comparison changed")
                self.locals[slot] = lhs

    def call(self, slot, call):
        target = call["func"]["Regular"]["kind"]["Fun"]
        args = list(map(self.value, call["args"]))
        if target == 20:
            require(not args, "unexpected zero argument")
            self.emit(slot, "zeroRegister")
        elif target == 21:
            self.emit(slot, f"{args[0]}.len.val")
        elif target == 22:
            bounds, stride = args
            self.emit(slot, f"(⟨{bounds}.1, {bounds}.2, {stride}⟩ : Cursor)")
        elif target in (23, 31, 34):
            self.locals[slot] = args[0]  # IntoIterator identity, byte view and signed cast
        elif target == 27:
            self.emit(slot, f"min {args[0]} {args[1]}")
        elif target in (4, 6):
            self.emit(slot, f"wordRange {' '.join(args)}", True)
        elif target in (29, 35):
            loader = "loadWords permit" if target == 29 else "loadRemote"
            self.code.append(f"  let (v{slot}, heap) ← {loader} heap {' '.join(args)}")
            self.locals[slot] = f"v{slot}"
        elif target == 30:
            self.emit(slot, f"sourceMask {args[0]}", True)
        elif target == 33:
            self.emit(slot, f"byteAdd {' '.join(args)}", True)
        elif target in (36, 38):
            self.emit(slot, ("xorValue" if target == 36 else "orValue") + " " + " ".join(args))
        elif target == 37:
            self.code.append(f"  let heap ← storeWords permit heap {' '.join(args)}")
            self.locals[slot] = "()"
        elif target == 25:
            require(args == ["state.any", "state.any"], "TEST must read the same register twice")
            self.locals[slot] = "testSelfNonzero state.any"
        else:
            raise ValueError("unsupported computational call")

    def block(self, statements):
        for stmt in statements:
            kind = stmt["kind"]
            if kind == "Return":
                continue
            tag, value = next(iter(kind.items()))
            if tag == "Assign":
                self.assign(local(value[0]), value[1])
            elif tag == "Call":
                self.call(local(value["dest"]), value["call"])
            else:
                require(tag in ("StorageLive", "StorageDead", "Borrowck", "Continue"),
                        "unsupported value-block statement")


def projection(document, source):
    translated = document["translated"]
    require(document["has_errors"] is False and translated["crate_name"] == "bulksketch",
            "unexpected or incomplete difference LLBC")
    target = translated["target_information"]
    require(len(target) == 1 and target[0]["key"] == "x86_64-apple-darwin"
            and target[0]["value"]["is_little_endian"] is True
            and target[0]["value"]["target_pointer_size"] == 8, "unexpected difference target")
    require(sha(source.encode()) == SOURCE_SHA
            and translated["files"][6]["name"] == {"Local": SOURCE}
            and translated["files"][6]["contents"] == source, "difference source pin mismatch")
    root = translated["fun_decls"][11]
    span = root["item_meta"]["span"]["Untagged"]["data"]
    lines = source.splitlines(keepends=True)
    begin, end = span["beg"], span["end"]
    original = (lines[begin["line"] - 1][begin["col"]:] + "".join(lines[begin["line"]:end["line"] - 1])
                + lines[end["line"] - 1][:end["col"]])
    require(span["file_id"] == 6 and original == root["item_meta"]["source_text"], "difference source span mismatch")
    statements = root["body"]["Structured"]["body"]["statements"]
    registry = deepcopy(document)
    registry["translated"]["fun_decls"][11]["body"]["Structured"]["body"]["statements"] = []
    require(digest(registry) == REGISTRY_SHA, "difference local, callee or target registry changed")
    # Pins the complete borrow/lifetime/cleanup trace as well as the control
    # nodes not emitted by the value-dataflow compiler.
    require(digest(statements) == TRACE_SHA, "difference typed trace changed")
    cut = next(i for i, stmt in enumerate(statements) if "Loop" in stmt["kind"])
    body = statements[cut]["kind"]["Loop"]["statements"]
    switch = next(i for i, stmt in enumerate(body) if "Switch" in stmt["kind"])
    require(body[switch]["kind"]["Switch"]["branches"][0]["statements"][0]["kind"] == {"Break": 0},
            "iterator None must break")
    literals = constants(document)
    inputs = {1: "inputs.dst", 2: "inputs.localWords", 3: "inputs.remoteBytes"}
    setup = Compiler(literals, inputs)
    setup.block(statements[:cut])
    step = Compiler(literals, {**inputs, 4: "state.any"})
    step.block(body[switch + 1:])
    finish = Compiler(literals, {4: "state.any"})
    finish.block(statements[cut+1:])
    return HEADER + (
        "def differenceSetup (inputs : Inputs) (heap : Memory) : Cursor × State :=\n" +
        "\n".join(setup.code) + f"\n  ({setup.locals[10]}, ⟨heap, {setup.locals[4]}⟩)\n\n" +
        "def differenceStep (inputs : Inputs) (permit : Nat → Bool) (offset : Nat) (state : State) :\n"
        "    Option State := do\n  let heap := state.heap\n" +
        "\n".join(step.code) + f"\n  some ⟨heap, {step.locals[4]}⟩\n\n" +
        "def differenceFinish (state : State) : Bool :=\n" +
        f"  {finish.locals[0]}\n\n" +
        "def differenceProgram (inputs : Inputs) (permit : Nat → Bool) (heap : Memory) :\n"
        "    Option (Bool × Memory) := do\n"
        "  let (cursor, state) := differenceSetup inputs heap\n"
        "  let state ← run (differenceStep inputs permit) cursor (cursor.stop + 1) state\n"
        "  some (differenceFinish state, state.heap)\n\n"
        "end BulksketchBridge.X86MaskedMemory.Difference\n")


def check(root=ROOT):
    receipt = json.loads((root / DIRECTORY / "receipt.json").read_text())
    artifacts = receipt["artifacts"]
    require(receipt["native_body_proof_credit"] == 0 and receipt["target"] == "x86_64-apple-darwin"
            and receipt["source_commit"] == "0a5bda53f6b07fcae8acd870e2d0c4a246d207e6"
            and receipt["registry_sha256"] == REGISTRY_SHA and receipt["llbc_sha256"] == LLBC_SHA
            and len(artifacts) == len(ARTIFACTS) and {item["path"] for item in artifacts} == ARTIFACTS,
            "difference LLBC receipt scope changed")
    for item in artifacts:
        require(sha((root / item["path"]).read_bytes()) == item["sha256"],
                "raw difference artifact changed: " + item["path"])
    raw = (root / DIRECTORY / "arithmetic.llbc").read_bytes()
    source = (root.parent.parent / SOURCE).read_text()
    require(sha(raw) == LLBC_SHA, "frozen difference LLBC changed")
    compiled = projection(json.loads(raw), source)
    require((root / PROGRAM).read_text() == compiled, "compiled difference LLBC program differs")
    return {"compiled_projection": str(PROGRAM), "projection_sha256": sha(compiled.encode()),
            "llbc_sha256": sha(raw), "source_sha256": SOURCE_SHA,
            "programs": {SOURCE_ID: "BulksketchBridge.X86MaskedMemory.Difference.differenceProgram"},
            "native_body_proof_credit": 0}


if __name__ == "__main__":
    print(json.dumps(check(), indent=2))
